#!/usr/bin/env node
// Recover verified arrival branches without changing archived questions/answers.
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path'),assert=require('node:assert/strict'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),engine=require('../site/routing.js'),diagram=require('../site/diagram.js');
function build(miura){
  const sandbox={window:{}};vm.runInNewContext(fs.readFileSync(path.join(root,'site/data/kyoto-network.js'),'utf8'),sandbox);
  const data={version:1,description:'Verified candidate arrival branches only; no exit routes or human answers.',datasets:{}};
  const focused=require('../site/data/evaluation-miura-focused-source.json'),cache=new Map();
  for(let number=2;number<=7;number++){
    const dataset=require('../site/data/evaluation-set-0'+number+'.json'),network=number<4?sandbox.window.KYOTO_NETWORK:miura,frames=new Map();
    if(number<=5){
      const g=engine.graph(network),nodes=[...g.adj.keys()].sort((a,b)=>a-b).map(id=>g.nodes.get(id));let state=number+41;
      const random=()=>((state=(Math.imul(state,1664525)+1013904223)>>>0)/4294967296);
      const maximum=Math.max(...dataset.pairs.map(p=>Number(p.context.courseId.split('-').at(-1))));
      for(let route=0;route<=maximum;route++){
        const locations=Array.from({length:4},(_,i)=>({...nodes[Math.floor(random()*nodes.length)],name:'評価用道路地点'+(i+1)}));
        const id='seed-'+(number+41)+'-route-'+route;if(dataset.pairs.some(p=>p.context.courseId===id))frames.set(id,engine.generate(network,locations).frames);
      }
    }
    const records={};
    for(const pair of dataset.pairs){
      let courseId=pair.context.courseId;
      if(number>=6){
        courseId=focused.sets[number-6].items.find(item=>item.pairId===pair.id).courseId;
        if(!cache.has(courseId))cache.set(courseId,engine.generate(miura,focused.courses.find(c=>c.id===courseId).locations).frames);
      }
      const frame=(number<6?frames:cache).get(courseId).find(f=>f.id===pair.context.candidateId&&Math.abs(f.at-pair.context.candidateAt)<.00001);
      assert(frame,'Candidate route not recovered: '+pair.id);assert.deepEqual(frame.branches,pair.modelInput.candidate.branches);
      assert.equal(frame.heading,pair.modelInput.candidate.heading);
      const index=engine.incomingBranchIndex(frame);assert.notEqual(index,null,'Ambiguous arrival branch: '+pair.id);
      records[pair.id]=[index,diagram.fingerprint(pair.modelInput.candidate)];
    }
    data.datasets[dataset.id]=records;
  }
  return data;
}
if(require.main===module){
  try{
    const input=process.argv[2];if(!input)throw Error('Usage: node scripts/create_incoming_roads.cjs miura-harbor-network.json');
    const raw=fs.readFileSync(input,'utf8');assert.equal(crypto.createHash('sha256').update(raw).digest('hex'),require('../site/data/evaluation-miura-source.json').extractSha256);
    const data=build(JSON.parse(raw));fs.writeFileSync(path.join(root,'site/data/evaluation-incoming-roads.js'),'// Generated by scripts/create_incoming_roads.cjs; arrival branches only.\nwindow.KOMA_INCOMING_ROADS='+JSON.stringify(data,null,2)+';\n');
    console.log('Recovered arrival branches for '+Object.values(data.datasets).reduce((n,d)=>n+Object.keys(d).length,0)+' archived pairs.');
  }catch(error){console.error(error.message);process.exitCode=1;}
}
module.exports={build};
